void ui_draw_cat_avatar(int x, int y, bool user_variant) {
    static uint16_t images[2][CAT_AVATAR_SIZE * CAT_AVATAR_SIZE];
    static bool initialized;
    static const uint16_t palette[] = {
        0x0000, 0xffff, 0x1084, 0x1947, 0x320b, 0x4cff, 0x1a6f, 0xfeca,
        0x66b5, 0xfdab, 0xfb70, 0xf7bf, 0xa579, 0x66dd, 0xd4de, 0x10e6,
    };
    if (!initialized) {
        for (int variant = 0; variant < 2; ++variant) {
            for (size_t pixel = 0; pixel < CAT_AVATAR_SIZE * CAT_AVATAR_SIZE; ++pixel) {
                uint8_t packed = s_cat_avatar_bitmap[pixel >> 1];
                uint8_t token = (pixel & 1) ? (packed & 15) : (packed >> 4);
                images[variant][pixel] = palette[token == CAT_FRAME_TOKEN
                    ? (variant ? UI_COLOR_PRIMARY_DARK : UI_COLOR_PANEL_ALT) : token];
            }
        }
        initialized = true;
    }
    ESP_ERROR_CHECK_WITHOUT_ABORT(ui_draw_rgb565_bitmap(
        x, y, CAT_AVATAR_SIZE, CAT_AVATAR_SIZE, images[user_variant ? 1 : 0],
        NULL, user_variant ? UI_COLOR_PRIMARY_DARK : UI_COLOR_PANEL_ALT));
}
